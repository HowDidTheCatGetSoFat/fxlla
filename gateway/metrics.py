"""Passive request metrics for the fxlla gateway.

Time to first token and tokens per second are derived from real proxied
traffic, with no synthetic probe, and appended to the same rolling time-series
(`stats.jsonl`) that `fxlla stats` writes and the menu bar app renders.

Standard library only. The functions here are pure and independently testable;
the gateway feeds streamed bytes to StreamMetrics and calls append_sample once
per completed request.
"""
import json
import math
import os
import threading
import time

# Appends come from many gateway handler threads in one process. Serializing
# append-plus-trim here removes the window where a trim's os.replace could drop
# a concurrent append.
_APPEND_LOCK = threading.Lock()


def stats_file():
    """Path of the stats time-series, matching the CLI's STATS_FILE.

    Honours FXLLA_STATS_FILE, then XDG_STATE_HOME, then ~/.local/state.
    """
    env = os.environ.get("FXLLA_STATS_FILE")
    if env:
        return env
    base = os.environ.get("XDG_STATE_HOME") or os.path.join(
        os.path.expanduser("~"), ".local", "state")
    return os.path.join(base, "fxlla", "stats.jsonl")


def is_completion_path(path):
    """True for the generative endpoints worth timing (chat and legacy text
    completions); false for embeddings, models, and health."""
    p = path.split("?", 1)[0].rstrip("/")
    return p.endswith("/chat/completions") or p.endswith("/completions")


# A reasoning model emits its thinking before the visible answer, and no two
# servers agree on the field: llama.cpp streams `reasoning_content`, mlx_lm
# streams `reasoning`. Both are generated tokens, and the server's own
# `completion_tokens` counts them - so a clock started at the first VISIBLE
# token divides every generated token by only the time the answer took.
# Measured on Gemma 4 26B-A4B: 563 reasoning deltas before 165 content ones,
# 733 tokens, 6.19 s of generation reported as 1.41 s. That is 518 tok/s from
# a model doing 114.
_REASONING_KEYS = ("reasoning_content", "reasoning")


def _delta_generated_text(obj):
    """Text GENERATED by one streamed chunk, chat or legacy completion.

    Chat streams put the answer under choices[].delta.content and the thinking
    under one of _REASONING_KEYS; legacy completions put text under
    choices[].text. Only string pieces count.

    This is deliberately everything the model produced rather than everything
    a reader sees: it decides when the decode clock starts, and the clock has
    to start at the first token the token COUNT is counting.
    """
    out = []
    for ch in obj.get("choices", []) or []:
        delta = ch.get("delta")
        if isinstance(delta, dict):
            for key in ("content",) + _REASONING_KEYS:
                piece = delta.get(key)
                if isinstance(piece, str):
                    out.append(piece)
            # A streamed tool call is generated tokens too, and a model can
            # emit a whole call before any prose - same shape of error as the
            # thinking above, reached through a different field.
            for call in delta.get("tool_calls") or []:
                if not isinstance(call, dict):
                    continue
                fn = call.get("function")
                if isinstance(fn, dict):
                    for key in ("name", "arguments"):
                        piece = fn.get(key)
                        if isinstance(piece, str):
                            out.append(piece)
        text = ch.get("text")
        if isinstance(text, str):
            out.append(text)
    return "".join(out)


def _usage_completion_tokens(obj):
    usage = obj.get("usage")
    if isinstance(usage, dict):
        ct = usage.get("completion_tokens")
        if isinstance(ct, int):
            return ct
    return None


def _int(v):
    # bool is an int subclass; a flag is not a count.
    return v if isinstance(v, int) and not isinstance(v, bool) else None


def _num(v):
    # json.loads accepts NaN and Infinity; they are not measurements.
    if isinstance(v, bool) or not isinstance(v, (int, float)):
        return None
    # isfinite converts to float, which overflows on a huge int; ints are finite.
    if isinstance(v, float) and not math.isfinite(v):
        return None
    return v


def _ms(v):
    v = _num(v)
    return None if v is None else int(round(v))


def _secs_ms(v):
    v = _num(v)
    # A huge finite value can overflow to inf once scaled; _num rejects that.
    return None if v is None else _ms(_num(v * 1000))


def _sub(d, key):
    d = d.get(key) if isinstance(d, dict) else None
    return d if isinstance(d, dict) else {}


def engine_report(usage, timings):
    """Normalize what an engine says about a request into fixed fields.

    Engines disagree on where they report: llama-server puts timings in a
    `timings` object (ms), omlx puts durations inside `usage` (seconds), mlx
    reports tokens only. A value the engine did not give stays None; nothing
    is estimated here.
    """
    usage = usage if isinstance(usage, dict) else {}
    timings = timings if isinstance(timings, dict) else {}
    cached = _int(_sub(usage, "prompt_tokens_details").get("cached_tokens"))
    if cached is None:
        cached = _int(timings.get("cache_n"))
    prompt_ms = _ms(timings.get("prompt_ms"))
    if prompt_ms is None:
        prompt_ms = _secs_ms(usage.get("prompt_eval_duration"))
    decode_ms = _ms(timings.get("predicted_ms"))
    if decode_ms is None:
        decode_ms = _secs_ms(usage.get("generation_duration"))
    prompt_tokens = _int(usage.get("prompt_tokens"))
    if prompt_tokens is None:
        # llama-server: prompt_n counts only the tokens it evaluated, the
        # cached ones are reported apart in cache_n.
        pn = _int(timings.get("prompt_n"))
        if pn is not None:
            prompt_tokens = pn + (_int(timings.get("cache_n")) or 0)
    output_tokens = _int(usage.get("completion_tokens"))
    if output_tokens is None:
        output_tokens = _int(timings.get("predicted_n"))
    return {
        "prompt_tokens": prompt_tokens,
        "cached_tokens": cached,
        "output_tokens": output_tokens,
        "reasoning_tokens": _int(_sub(usage, "completion_tokens_details").get("reasoning_tokens")),
        "prompt_ms": prompt_ms,
        "decode_ms": decode_ms,
        "draft_tokens": _int(timings.get("draft_n")),
        "draft_accepted": _int(timings.get("draft_n_accepted")),
    }


# Above this, the number is describing the transport rather than the model:
# nothing decoding locally on Apple Silicon approaches it, so a rate past it
# means the stream arrived in one piece and the timestamps collapsed.
IMPLAUSIBLE_TPS = 2000


class StreamMetrics:
    """Accumulate streamed SSE bytes and track first token and token count.

    The token count approximates one token per streamed delta, matching how the
    active probe counts. When the server emits a trailing usage chunk
    (stream_options.include_usage), its exact completion_tokens takes over.
    """

    def __init__(self, start):
        self.start = start          # time.monotonic() at request dispatch
        self.first = None           # time.monotonic() of the first token
        self.deltas = 0
        self.usage_tokens = None
        self.usage = None           # last `usage` object the stream carried
        self.timings = None         # last `timings` object the stream carried
        self.finish = None          # last non-empty finish_reason
        self._buf = ""

    def feed(self, chunk_bytes):
        self._buf += chunk_bytes.decode("utf-8", "ignore")
        while "\n" in self._buf:
            line, self._buf = self._buf.split("\n", 1)
            self._line(line.strip())

    def _line(self, line):
        if not line.startswith("data:"):
            return
        data = line[5:].strip()
        if not data or data == "[DONE]":
            return
        try:
            obj = json.loads(data)
        except ValueError:
            return
        if not isinstance(obj, dict):
            return
        ct = _usage_completion_tokens(obj)
        if ct is not None:
            self.usage_tokens = ct
        if isinstance(obj.get("usage"), dict):
            self.usage = obj["usage"]
        if isinstance(obj.get("timings"), dict):
            self.timings = obj["timings"]
        for ch in obj.get("choices") or []:
            if isinstance(ch, dict):
                fr = ch.get("finish_reason")
                if isinstance(fr, str) and fr:
                    self.finish = fr
        if _delta_generated_text(obj):
            if self.first is None:
                self.first = time.monotonic()
            self.deltas += 1

    def report(self):
        """What the engine said about this request, in fixed fields."""
        return engine_report(self.usage, self.timings)

    def result(self, end):
        """Return (ttft_ms, tps, tokens); ttft/tps are None when unmeasurable.

        A decode rate needs the tokens to have ARRIVED spread over time. When a
        response comes back buffered - one read carrying the whole stream - all
        the deltas are parsed microseconds apart, so the first-token timestamp
        lands next to the last and the division explodes. One real measurement
        here reported 1,865,386 tokens/s that way, and it dragged the median it
        was pooled into with it.

        There is no local decode anywhere near IMPLAUSIBLE_TPS on this
        hardware, so a computed rate above it is a statement about buffering
        rather than about the model. Reported as unmeasurable instead: fewer
        honest samples beat more invented ones, and the caller already knows
        how to skip a None.
        """
        tokens = self.usage_tokens if self.usage_tokens is not None else self.deltas
        ttft_ms = int((self.first - self.start) * 1000) if self.first else None
        gen = (end - self.first) if self.first else 0
        tps = None
        # Two arrivals at minimum: a rate is measured BETWEEN token arrivals,
        # and one of them times nothing.
        if gen > 0 and tokens and self.deltas > 1:
            rate = tokens / gen
            if rate <= IMPLAUSIBLE_TPS:
                tps = round(rate, 1)
        return ttft_ms, tps, tokens


class UsageChunkStripper:
    """Remove the usage-only SSE event the gateway asked the engine for.

    When the gateway injects stream_options.include_usage, the engine appends
    one event with `choices == []` and a `usage` key that the client never
    requested. This drops exactly those events and passes every other byte
    through unchanged and in order. A complete event is emitted at once; only
    an incomplete tail is held back, so streaming stays incremental.
    """

    def __init__(self):
        self._buf = b""

    @staticmethod
    def _is_usage_only(event):
        data = []
        for line in event.splitlines():
            if line.startswith(b"data:"):
                data.append(line[5:].strip())
        if not data:
            return False
        try:
            obj = json.loads(b"\n".join(data))
        except ValueError:
            return False
        return (isinstance(obj, dict) and obj.get("choices") == []
                and "usage" in obj)

    def consume(self, data):
        self._buf += data
        out = []
        while True:
            hits = [(i, len(t)) for t in (b"\r\n\r\n", b"\n\n")
                    for i in [self._buf.find(t)] if i >= 0]
            if not hits:
                break
            i, n = min(hits)
            event, self._buf = self._buf[:i + n], self._buf[i + n:]
            if not self._is_usage_only(event):
                out.append(event)
        return b"".join(out)

    def finish(self):
        tail, self._buf = self._buf, b""
        return tail

    def held(self):
        """The incomplete tail kept back so far."""
        return self._buf


def usage_from_json(body_bytes):
    """completion_tokens from a non-streamed response body, or None."""
    try:
        obj = json.loads(body_bytes)
    except (ValueError, TypeError):
        return None
    return _usage_completion_tokens(obj)


def build_sample(ts, model, engine, ram_mb, ttft_ms, tps, **extra):
    """One time-series row, shaped like the CLI probe plus a source marker.

    `extra` fields are merged after the base keys, which cannot be overridden.
    """
    row = {
        "ts": int(ts),
        "model": model,
        "engine": engine,
        "ram_mb": int(ram_mb) if ram_mb is not None else None,
        "ttft_ms": ttft_ms,
        "tps": tps,
        "source": "gateway",
    }
    for k, v in extra.items():
        row.setdefault(k, v)
    return row


def _maybe_trim(path, cap):
    """Keep the newest `cap` lines. Guarded by size so most appends do no I/O."""
    try:
        if os.path.getsize(path) < cap * 120:
            return
        with open(path, encoding="utf-8") as f:
            lines = f.readlines()
        if len(lines) <= cap:
            return
        tmp = path + ".tmp"
        with open(tmp, "w", encoding="utf-8") as f:
            f.writelines(lines[-cap:])
        os.replace(tmp, path)
    except OSError:
        pass


def append_sample(path, sample, cap=5000):
    """Append one JSONL sample and trim the file to the newest `cap` lines."""
    d = os.path.dirname(path)
    if d:
        os.makedirs(d, exist_ok=True)
    line = json.dumps(sample) + "\n"
    with _APPEND_LOCK:
        with open(path, "a", encoding="utf-8") as f:
            f.write(line)
        _maybe_trim(path, cap)
